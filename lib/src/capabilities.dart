library;

enum CapabilityTier { public, authenticated, wallet, execution, bridge }

enum CapabilityOperation {
  list,
  get,
  search,
  read,
  stream,
  derive,
  sign,
  create,
  submit,
  cancel,
  update,
  simulate,
}

enum CapabilityTransport { local, https, wss, rpc }

enum AuthRequirement { none, l1, l2, siwe }

enum SigningRequirement { none, wallet }

enum CapabilityStatus { implemented, dtoOnly, unsupported, planned }

final class Capability {
  const Capability({
    required this.id,
    required this.tier,
    required this.service,
    required this.operation,
    required this.transport,
    required this.auth,
    required this.signing,
    required this.mutates,
    required this.cliCommand,
    required this.extension,
    required this.summary,
    required this.status,
  });
  final String id;
  final CapabilityTier tier;
  final String service;
  final CapabilityOperation operation;
  final CapabilityTransport transport;
  final List<AuthRequirement> auth;
  final SigningRequirement signing;
  final bool mutates;
  final List<String>? cliCommand;
  final bool extension;
  final String summary;
  final CapabilityStatus status;
  Map<String, dynamic> toJson() => {
    'id': id,
    'tier': tier.name,
    'service': service,
    'operation': operation.name,
    'transport': transport.name,
    'auth': auth.map((value) => value.name).toList(growable: false),
    'signing': signing.name,
    'mutates': mutates,
    'cliCommand': cliCommand,
    'extension': extension,
    'summary': summary,
    'status': status.name,
  };
}

