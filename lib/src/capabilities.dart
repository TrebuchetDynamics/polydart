  static Capability? byId(String id) {
    var low = 0;
    var high = all.length - 1;
    while (low <= high) {
      final middle = (low + high) >> 1;
      final comparison = all[middle].id.compareTo(id);
      if (comparison == 0) return all[middle];
      if (comparison < 0) {
        low = middle + 1;
      } else {
        high = middle - 1;
      }
    }
    return null;
  }
